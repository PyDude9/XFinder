import SwiftUI
import AppKit

/// Sidebar-hosted settings. The four CÀI ĐẶT destinations share one page
/// scaffold; each renders its pane as bodies using the same SettingsCard /
/// ToggleRow components the system pages use. Preferences persist via
/// `@AppStorage` (UserDefaults); the two that touch the running app — theme
/// and Dock visibility — apply live through AppKit.
struct SettingsDetailView: View {
    let destination: SidebarDestination

    var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: 16) {
                Text(destination.titleVI)
                    .font(.system(size: 22, weight: .bold))
                    .padding(.horizontal, 20)
                    .padding(.top, 16)

                Group {
                    switch destination {
                    case .settingsClipboard:  ClipboardSettingsBody()
                    case .settingsMenubar:    MenubarSettingsBody()
                    default:                  EmptyView()
                    }
                }
                .padding(.horizontal, 20)
                .padding(.bottom, 20)
            }
        }
        .background(Color(.windowBackgroundColor))
    }
}

// `GeneralSettingsBody` was deleted along with the `settingsGeneral`
// destination. Its two controls were duplicates: the theme picker is on
// Điều khiển nhanh (which applies it system-wide, not just to XFinder) and the
// Dock-icon toggle is on Tổng quan. `AppearanceController`/`DockController`
// below are still used — by launch-time restore and by those pages.

// MARK: - Clipboard

private struct ClipboardSettingsBody: View {
    @AppStorage("clipboard.captureImages") private var captureImages = true
    @AppStorage("clipboard.captureLinks") private var captureLinks = true
    @AppStorage("clipboard.enableOCR") private var enableOCR = true
    @AppStorage("clipboard.maxHistory") private var maxHistory = 1000
    @AppStorage("clipboard.autoDeleteDays") private var autoDeleteDays = 30
    @AppStorage("clipboard.sounds") private var sounds = true
    /// Privacy lives here, not on its own page: excluding password managers is
    /// a property of *what the clipboard records*, not a separate feature.
    @AppStorage("privacy.excludePasswordManagers") private var excludePW = true
    @AppStorage("sync.icloudClipboard") private var icloudSync = false
    @State private var cloud = CloudSyncController.shared

    private static func time(_ d: Date) -> String {
        let f = DateFormatter(); f.dateStyle = .short; f.timeStyle = .short
        return f.string(from: d)
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 16) {
            SettingsCard(title: "Riêng tư",
                         subtitle: "Ứng dụng không bao giờ được ghi vào Clipboard.") {
                VStack(alignment: .leading, spacing: 8) {
                    ToggleRow(title: "Bỏ qua trình quản lý mật khẩu",
                              subtitle: "1Password, Bitwarden, LastPass, KeePassXC, Dashlane, Keychain",
                              isOn: $excludePW)
                    Text("Ngoài ra XFinder luôn bỏ qua nội dung được đánh dấu Concealed / AutoGenerated / Transient, kể cả khi tắt công tắc trên.")
                        .font(.system(size: 11)).foregroundColor(.secondary)
                    Text("Toàn bộ dữ liệu nằm trên máy này. Không telemetry, không gửi lên server.")
                        .font(.system(size: 11)).foregroundColor(.secondary)
                }
            }

            SettingsCard(title: "Đồng bộ iCloud",
                         subtitle: "Cho ứng dụng Clipboard trên iPhone sau này.") {
                VStack(alignment: .leading, spacing: 8) {
                    ToggleRow(title: "Đồng bộ clipboard qua iCloud", isOn: $icloudSync)
                        .onChange(of: icloudSync) { CloudSyncController.shared.applySettings() }

                    switch cloud.status {
                    case .disabled:
                        Text("Đang tắt.").font(.system(size: 11)).foregroundColor(.secondary)
                    case .unavailable(let why):
                        Text(why).font(.system(size: 11)).foregroundColor(.orange)
                    case .ready(let count, let last):
                        Text("Sẵn sàng — \(count) mục trên iCloud" +
                             (last.map { " · lần cuối " + Self.time($0) } ?? ""))
                            .font(.system(size: 11)).foregroundColor(.green)
                    }

                    Text("Dùng iCloud Key-Value Store: giới hạn 1 MB của Apple nên **chỉ đồng bộ văn bản** (tối đa 60 mục, mỗi mục 2000 ký tự). Ảnh và tệp luôn ở lại máy Mac.")
                        .font(.system(size: 11)).foregroundColor(.secondary)
                    Text("Cần entitlement iCloud + tài khoản Apple Developer trả phí. Khi chưa có, công tắc sẽ báo rõ thay vì giả vờ đồng bộ.")
                        .font(.system(size: 11)).foregroundColor(.secondary)
                }
            }

            SettingsCard(title: "Thu thập") {
                VStack(spacing: 10) {
                    ToggleRow(title: "Ảnh chụp / hình ảnh", isOn: $captureImages)
                    ToggleRow(title: "Đường link", isOn: $captureLinks)
                    ToggleRow(title: "Nhận diện chữ (OCR)", subtitle: "Vision Framework", isOn: $enableOCR)
                    ToggleRow(title: "Âm thanh khi sao chép/dán", subtitle: "Tink/Pop hệ thống", isOn: $sounds)
                }
            }

            SettingsCard(title: "Lịch sử") {
                VStack(alignment: .leading, spacing: 14) {
                    VStack(alignment: .leading, spacing: 4) {
                        Text("Giữ \(maxHistory) mục").font(.system(size: 13, weight: .medium))
                        Slider(value: Binding(get: { Double(maxHistory) }, set: { maxHistory = Int($0) }),
                               in: 100...10000, step: 100)
                    }
                    VStack(alignment: .leading, spacing: 4) {
                        Text("Tự xóa sau \(autoDeleteDays) ngày").font(.system(size: 13, weight: .medium))
                        Slider(value: Binding(get: { Double(autoDeleteDays) }, set: { autoDeleteDays = Int($0) }),
                               in: 1...365)
                    }
                }
            }
        }
        .onAppear { cloud.applySettings() }
    }
}

// MARK: - Menubar

private struct MenubarSettingsBody: View {
    @AppStorage("menubar.showBattery") private var showBattery = true
    @AppStorage("menubar.showNetwork") private var showNetwork = true
    @AppStorage("menubar.updateInterval") private var updateInterval = 2

    var body: some View {
        VStack(alignment: .leading, spacing: 16) {
            SettingsCard(title: "Thông tin trên flyout") {
                VStack(spacing: 10) {
                    ToggleRow(title: "Pin", isOn: $showBattery)
                    ToggleRow(title: "Tốc độ mạng", isOn: $showNetwork)
                }
            }
            SettingsCard(title: "Tần suất cập nhật", subtitle: "\(updateInterval) giây") {
                Picker("Cập nhật", selection: $updateInterval) {
                    Text("1 giây").tag(1)
                    Text("2 giây").tag(2)
                    Text("5 giây").tag(5)
                }
                .pickerStyle(.segmented)
                .onChange(of: updateInterval) { SystemMonitorManager.shared.applyUpdateInterval() }
            }
        }
    }
}

// MARK: - AppKit side effects

@MainActor
enum AppearanceController {
    static func apply(_ theme: String) {
        switch theme {
        case "Light": NSApp.appearance = NSAppearance(named: .aqua)
        case "Dark":  NSApp.appearance = NSAppearance(named: .darkAqua)
        default:      NSApp.appearance = nil
        }
    }
}

@MainActor
enum DockController {
    static func apply(_ show: Bool) {
        NSApp.setActivationPolicy(show ? .regular : .accessory)
    }
}
