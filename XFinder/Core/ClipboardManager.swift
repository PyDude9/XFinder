    /// D — import from an `.xfinderclip`: new records are merged by timestamp (never replacing an
    /// existing id), new boards appended, everything persisted. The cap still applies.
    func importRecords(_ records: [ClipboardRecord], boards: [Pinboard]) {
        let existing = Set(history.map(\.id))
        let fresh = records.filter { !existing.contains($0.id) }
        if !fresh.isEmpty {
            history = (history + fresh).sorted { $0.timestamp > $1.timestamp }
            trimToCap()
            Task {
                for r in fresh { _ = await DatabaseService.shared.insertClipboardRecord(r) }
            }
        }
        let knownBoards = Set(pinboards.map(\.id))
        let newBoards = boards.filter { !knownBoards.contains($0.id) }
        if !newBoards.isEmpty {
            pinboards.append(contentsOf: newBoards)
            savePinboards()
        }
    }

    private func savePinboards() {
        if let encoded = try? JSONEncoder().encode(pinboards) {
            UserDefaults.standard.set(encoded, forKey: "XFinder.Pinboards")
        }
    }

    /// Hydrate from SQLite (was a placeholder that dropped all history).
    private func loadHistoryFromDB() {
        Task {
            let cap = historyCap
            let rows = await DatabaseService.shared.fetchClipboardRecords(limit: cap > 0 ? cap : -1)   // SQLite: LIMIT -1 = all
            await MainActor.run {
                // Purge rows whose image files vanished completely (stale disk refs).
                self.history = rows.filter { r in
                    guard r.type == .image else { return true }
                    if let p = r.payloadPath, self.fileManager.fileExists(atPath: p) { return true }
                    if let t = r.thumbnailPath, self.fileManager.fileExists(atPath: t) { return true }
                    return false
                }
                self.trimToCap()
            }
        }
    }

    // No `deinit`: this is a `shared` singleton that lives for the whole
    // process, so it never runs — and reaching main-actor state from a
    // nonisolated deinit is an error under strict concurrency.
}
