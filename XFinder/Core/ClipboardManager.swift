    // MARK: - Monitoring (guide §6: zero polling)

    private var lastChangeCount: Int = NSPasteboard.general.changeCount
    private var monitorTimer: Timer?
    private var consecutiveNoChange = 0
    private var observers: [NSObjectProtocol] = []
    private let fileManager = FileManager.default

    private init() {
        loadPinboards()
        currentPinboardID = pinboards.first?.id
        setupEventDrivenMonitoring()
        loadHistoryFromDB()
        purgeExpired()
    }

    /// App-activation + sleep/wake events drive checks; the timer is only a
    /// backoff safety net (0.25 s → 1 s → 5 s). Every event path calls
    /// `wakeAndCheck()`, which resets the backoff — otherwise the 5 s floor
    /// would persist right after the user copied something.
    private func setupEventDrivenMonitoring() {
        let nc = NSWorkspace.shared.notificationCenter
        let center = NotificationCenter.default
        observers = [
            nc.addObserver(forName: NSWorkspace.didActivateApplicationNotification,
                           object: nil, queue: .main) { [weak self] note in
                // Pull the value out *here* rather than sending the whole
                // non-Sendable `Notification` into the Task — that is a real
                // data race, not just an isolation complaint.
                let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
                let pid = app?.processIdentifier
                let policy = app?.activationPolicy
                Task { @MainActor in
                    self?.noteAppActivation(pid: pid, policy: policy)
                    self?.wakeAndCheck()
                }
            },
            center.addObserver(forName: NSApplication.didBecomeActiveNotification,
                               object: nil, queue: .main) { [weak self] _ in
                Task { @MainActor in self?.wakeAndCheck() }
            },
            nc.addObserver(forName: NSWorkspace.didWakeNotification,
                           object: nil, queue: .main) { [weak self] _ in
                Task { @MainActor in self?.wakeAndCheck() }
            },
        ]
        scheduleBackoffCheck(interval: 0.25)
    }

    /// Checks immediately and returns the poll to its fast cadence.
    private func wakeAndCheck() {
        _ = checkPasteboard()
        consecutiveNoChange = 0
        scheduleBackoffCheck(interval: 0.25)
    }

    private func scheduleBackoffCheck(interval: TimeInterval) {
        monitorTimer?.invalidate()
        monitorTimer = Timer.scheduledTimer(withTimeInterval: interval, repeats: false) { [weak self] _ in
            Task { @MainActor in
                guard let self else { return }
                let changed = self.checkPasteboard()
                self.consecutiveNoChange = changed ? 0 : self.consecutiveNoChange + 1
                // 0.25s while active, then back off hard: 1s, then 5s once the
                // pasteboard has been quiet for ~30 ticks. A permanent 1s floor
                // was measurably the app's last idle CPU cost. Nothing is missed
                // — app activation, app deactivation and wake all force an
                // immediate check, and a copy is almost always followed by a
                // switch to the app being pasted into.
                let n = self.consecutiveNoChange
                let next: TimeInterval = n > 30 ? 5.0 : (n > 8 ? 1.0 : 0.25)
                self.scheduleBackoffCheck(interval: next)
            }
        }
    }

    /// Track the last external app so paste targets it, not XFinder itself.
    /// Takes plain values, never the `Notification` — see the observer above.
    private func noteAppActivation(pid: pid_t?, policy: NSApplication.ActivationPolicy?) {
        let mine = ProcessInfo.processInfo.processIdentifier
        if let pid, pid != mine, policy == .regular {
            lastExternalPID = pid
        }
    }

    /// D1 #14 — the ONE reader of `clipboard.paused`: while on, nothing is recorded (the change count
    /// still advances so un-pausing does not swallow the stale item as new). Auto-clear still runs.
    var isPaused: Bool { UserDefaults.standard.object(forKey: "clipboard.paused") as? Bool ?? false }

    @discardableResult
    private func checkPasteboard() -> Bool {
        let pb = NSPasteboard.general
        let now = pb.changeCount
        guard now != lastChangeCount else { return false }
        lastChangeCount = now
        if !isPaused { captureClipboardContent() }
        // After capture, not before: cleaning may have rewritten the pasteboard (new count), and
        // a copy that was NOT ingested (concealed / password-manager) still needs its timer —
        // that is the copy auto-clear matters most for.
        scheduleAutoClear()
        return true
    }

    // MARK: - Auto-clear (opt-in, one-shot)

    /// When the macOS clipboard was last auto-cleared this session; nil until it happens, so the
    /// settings page can show that the app wiped something rather than ask to be trusted.
    private(set) var lastAutoClear: Date?
    private var autoClearWork: DispatchWorkItem?

    /// `clipboard.autoClearSeconds` (default **0** = off). Arms ONE timer for the pasteboard as
    /// it is now; a newer copy cancels it and arms its own. The rules live in
    /// `ClipboardAutoClear` (pure, tested): never clear a count that has moved, never arm for an
    /// empty pasteboard (our own `clearContents()` is a change too). No polling.
    ///
    /// This clears the **system pasteboard only**. XFinder's own history keeps the record — the
    /// setting's copy says so; claiming otherwise would be false.
    private func scheduleAutoClear() {
        autoClearWork?.cancel()
        autoClearWork = nil
        let seconds = UserDefaults.standard.object(forKey: "clipboard.autoClearSeconds") as? Int ?? 0
        let pb = NSPasteboard.general
        guard ClipboardAutoClear.shouldArm(setting: seconds, pasteboardIsEmpty: (pb.types ?? []).isEmpty),
              let delay = ClipboardAutoClear.delay(forSetting: seconds) else { return }
        let armed = pb.changeCount
        let work = DispatchWorkItem { [weak self] in
            // Main queue by construction; assumeIsolated keeps the @MainActor state honest.
            MainActor.assumeIsolated {
                guard let self else { return }
                let pb = NSPasteboard.general
                guard ClipboardAutoClear.shouldClear(armedChangeCount: armed,
                                                     currentChangeCount: pb.changeCount,
                                                     pasteboardIsEmpty: (pb.types ?? []).isEmpty) else { return }
                pb.clearContents()
                // Our own clear is a change: consume it so the monitor neither ingests an empty
                // pasteboard nor arms a timer for it.
                self.lastChangeCount = pb.changeCount
                self.lastAutoClear = Date()
                self.autoClearWork = nil
            }
        }
        autoClearWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + delay, execute: work)
    }

    // MARK: - Link cleaning (opt-in)

    /// What the last cleaning removed, for the Clipboard settings page. nil until a link was
    /// cleaned this session — so the user can see the app changed their clipboard, not just
    /// trust that it did something.
    private(set) var lastCleanedLink: URLCleaner.Result?

    /// `clipboard.cleanURLs` (default **false**: it rewrites what the user copied, so it must be
    /// asked for). When the whole copy is one link carrying listed tracking parameters, the
    /// pasteboard is rewritten with the cleaned link and that is what history records.
    ///
    /// Skipped when the change was XFinder's own write (`OwnWriteMark`): the paste engine writes
    /// and sends ⌘V ~150 ms later, and rewriting the pasteboard under the target app's read
    /// would paste an empty or half-written clipboard.
    private func applyLinkCleaning(to text: String, pasteboard pb: NSPasteboard, defaults: UserDefaults) -> String {
        guard defaults.object(forKey: "clipboard.cleanURLs") as? Bool ?? false,
              !OwnWriteMark.shared.contains(pb.changeCount),
              let result = URLCleaner.clean(text) else { return text }
        pb.clearContents()
        pb.setString(result.cleaned, forType: .string)
        pb.setString(result.cleaned, forType: .URL)
        // Our own rewrite bumped changeCount: consume it so the monitor does not ingest it as
        // a second copy of the same link.
        lastChangeCount = pb.changeCount
        lastCleanedLink = result
        return result.cleaned
    }

    // MARK: - Capture

    private func captureClipboardContent() {
        let pb = NSPasteboard.general
        let types = pb.types ?? []

        // 7a. Never ingest secrets (Apple pasteboard convention, transient and password manager types).
        for t in types {
            let lower = t.rawValue.lowercased()
            for kw in Self.sensitiveTypeKeywords {
                if lower.contains(kw) { return }
            }
        }

        let front = NSWorkspace.shared.frontmostApplication
        let bundleID = front?.bundleIdentifier
        let appName = front?.localizedName
        let bid = (bundleID ?? "").lowercased()
        let name = (appName ?? "").lowercased()
        let exe = (front?.executableURL?.lastPathComponent ?? "").lowercased()

        // Exclude password managers (bundle ID, app name, executable name)
        if UserDefaults.standard.object(forKey: "privacy.excludePasswordManagers") as? Bool ?? true {
            for kw in Self.excludedAppKeywords {
                if bid.contains(kw) || name.contains(kw) || exe.contains(kw) {
                    return
                }
            }
        }

        // User-defined excluded apps (matching bundle ID, app name, or executable name)
        let customRaw = UserDefaults.standard.string(forKey: "clipboard.customExcludedApps") ?? ""
        if !customRaw.isEmpty {
            let customList = customRaw.split(separator: ",").map {
                $0.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
            }.filter { !$0.isEmpty }
            for pattern in customList {
                if bid.contains(pattern) || name.contains(pattern) || exe.contains(pattern) {
                    return
                }
            }
        }

        let defaults = UserDefaults.standard

        let captureImages = defaults.object(forKey: "clipboard.captureImages") as? Bool ?? true
        let captureLinks = defaults.object(forKey: "clipboard.captureLinks") as? Bool ?? true
        let enableOCR = defaults.object(forKey: "clipboard.enableOCR") as? Bool ?? true
        let excludeCreditCards = defaults.object(forKey: "clipboard.excludeCreditCards") as? Bool ?? true
        let imageExtensions: Set<String> = ["png", "jpg", "jpeg", "heic", "tiff", "tif", "gif", "webp", "bmp", "ico", "svg", "icns"]

        // 1. File URLs (e.g. copying screenshot files or image files in Finder)
        var fileURLs: [URL] = []
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: nil) as? [URL], !urls.isEmpty {
            fileURLs = urls.filter { $0.isFileURL }
        }
        if fileURLs.isEmpty, let files = pb.propertyList(forType: .init("NSFilenamesPboardType")) as? [String] {
            fileURLs = files.map { URL(fileURLWithPath: $0) }
        }

        if let first = fileURLs.first {
            guard !isDuplicateContent(first.path) else { return }

            let ext = first.pathExtension.lowercased()
            if captureImages && imageExtensions.contains(ext),
               let img = NSImage(contentsOfFile: first.path) ?? NSImage(contentsOf: first) {
                let stored = ClipboardPayloadStore.storeImage(img)
                let rep = img.representations.first(where: { $0.pixelsWide > 0 && $0.pixelsHigh > 0 })
                let w = rep?.pixelsWide ?? Int(img.size.width)
                let h = rep?.pixelsHigh ?? Int(img.size.height)
                let record = ClipboardRecord(
                    type: .image,
                    sourceBundleID: bundleID, sourceAppName: appName,
                    textSnippet: first.lastPathComponent,
                    thumbnailPath: stored?.thumb,
                    payloadPath: first.path,
                    metadata: [
                        "width": "\(w)",
                        "height": "\(h)",
                        "dimensions": "\(w)×\(h)",
                        "path": first.path
                    ]
                )
                addToHistory(record)
                ClipboardSounds.playCopy()
                if enableOCR {
                    let rid = record.id
                    let ocrPath = stored?.payload ?? first.path
                    Task.detached(priority: .background) {
                        if let ocr = ClipboardOCR.recognizeText(atPath: ocrPath) {
                            await MainActor.run {
                                ClipboardManager.shared.applyOCR(rid, text: ocr)
                            }
                        }
                    }
                }
                return
            }

            // Non-image file
            let record = ClipboardRecord(
                type: .file,
                sourceBundleID: bundleID, sourceAppName: appName,
                textSnippet: fileURLs.count > 1 ? "\(first.lastPathComponent) (+\(fileURLs.count - 1))" : first.lastPathComponent,
                payloadPath: first.path,
                metadata: ["path": first.path, "count": "\(fileURLs.count)"]
            )
            addToHistory(record)
            ClipboardSounds.playCopy()
            return
        }

        // 2. Raw image on pasteboard (e.g. direct screenshot shortcut ⌘⌃⇧4, browser image copy)
        let isFinderIcon = (bundleID == "com.apple.finder") && (types.contains(NSPasteboard.PasteboardType("com.apple.finder.noderef")) || types.contains(NSPasteboard.PasteboardType("com.apple.icns")))
        if captureImages, !isFinderIcon,
           types.contains(.tiff) || types.contains(.png) || types.contains(NSPasteboard.PasteboardType("public.jpeg")),
           let image = NSImage(pasteboard: pb) {

            let stored = ClipboardPayloadStore.storeImage(image)
            let rep = image.representations.first(where: { $0.pixelsWide > 0 && $0.pixelsHigh > 0 })
            let w = rep?.pixelsWide ?? Int(image.size.width)
            let h = rep?.pixelsHigh ?? Int(image.size.height)
            let isScreenshot = (bundleID?.contains("screencapture") == true)
            let record = ClipboardRecord(
                type: .image,
                sourceBundleID: bundleID, sourceAppName: appName,
                textSnippet: isScreenshot ? "Chụp màn hình" : "Image",
                thumbnailPath: stored?.thumb, payloadPath: stored?.payload,
                metadata: ["width": "\(w)",
                           "height": "\(h)",
                           "dimensions": "\(w)×\(h)"]
            )
            addToHistory(record)
            ClipboardSounds.playCopy()
            if enableOCR, let payload = stored?.payload {
                let rid = record.id
                Task.detached(priority: .background) {
                    if let ocr = ClipboardOCR.recognizeText(atPath: payload) {
                        await MainActor.run {
                            ClipboardManager.shared.applyOCR(rid, text: ocr)
                        }
                    }
                }
            }
            return
        }

        // 3. String content (text, code, links, or text file paths)
        if types.contains(.string),
           let original = pb.string(forType: .string), !original.isEmpty {
            if excludeCreditCards && ClipboardClassifier.looksLikeCreditCard(original) { return }
            // Opt-in link cleaning runs AFTER the privacy checks above (a secret never reaches
            // it) and BEFORE the duplicate check, so history stores what was actually pasted.
            let text = applyLinkCleaning(to: original, pasteboard: pb, defaults: defaults)

            // Check if string is a direct path to an image file or filename on Desktop
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            var possiblePath = trimmed
            if possiblePath.hasPrefix("file://"), let u = URL(string: possiblePath) {
                possiblePath = u.path
            }
            if !possiblePath.hasPrefix("/") {
                let desk = FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Desktop").appendingPathComponent(possiblePath).path
                if FileManager.default.fileExists(atPath: desk) {
                    possiblePath = desk
                } else if FileManager.default.fileExists(atPath: desk + ".png") {
                    possiblePath = desk + ".png"
                }
            }
            if possiblePath.hasPrefix("/") && FileManager.default.fileExists(atPath: possiblePath) {
                let ext = URL(fileURLWithPath: possiblePath).pathExtension.lowercased()
                if captureImages && imageExtensions.contains(ext),
                   let img = NSImage(contentsOfFile: possiblePath) {
                    guard !isDuplicateContent(possiblePath) else { return }
                    let stored = ClipboardPayloadStore.storeImage(img)
                    let rep = img.representations.first(where: { $0.pixelsWide > 0 && $0.pixelsHigh > 0 })
                    let w = rep?.pixelsWide ?? Int(img.size.width)
                    let h = rep?.pixelsHigh ?? Int(img.size.height)
                    let record = ClipboardRecord(
                        type: .image,
                        sourceBundleID: bundleID, sourceAppName: appName,
                        textSnippet: URL(fileURLWithPath: possiblePath).lastPathComponent,
                        thumbnailPath: stored?.thumb,
                        payloadPath: possiblePath,
                        metadata: [
                            "width": "\(w)",
                            "height": "\(h)",
                            "dimensions": "\(w)×\(h)",
                            "path": possiblePath
                        ]
                    )
                    addToHistory(record)
                    ClipboardSounds.playCopy()
                    if enableOCR, let payload = stored?.payload {
                        let rid = record.id
                        Task.detached(priority: .background) {
                            if let ocr = ClipboardOCR.recognizeText(atPath: payload) {
                                await MainActor.run {
                                    ClipboardManager.shared.applyOCR(rid, text: ocr)
                                }
                            }
                        }
                    }
                    return
                }
            }

            guard !isDuplicateContent(text) else { return }

            let kind = ClipboardClassifier.classify(text: text)
            if kind == .link, !captureLinks { return }
            // The snippet is a preview; anything longer is kept whole in a payload file (see ClipboardText).
            var payloadPath: String?
            if ClipboardText.needsPayload(text) {
                payloadPath = ClipboardPayloadStore.storeText(text)
            }
            var meta = ["length": "\(text.count)",
                        "url": kind == .link ? text.trimmingCharacters(in: .whitespacesAndNewlines) : ""]
            // B5 "Đi tới nguồn": Chromium-based browsers attach the page a selection was copied from
            // (measured on this Mac: `org.chromium.source-url`, plain text, no entitlement). Safari's
            // equivalent is unverified, so only this one type is read; nothing is guessed.
            if let src = pb.string(forType: NSPasteboard.PasteboardType("org.chromium.source-url")),
               let u = URL(string: src), ["http", "https"].contains(u.scheme ?? "") {
                meta["sourceURL"] = src
            }
            let record = ClipboardRecord(
                type: kind,
                sourceBundleID: bundleID, sourceAppName: appName,
                textSnippet: ClipboardText.preview(text),
                payloadPath: payloadPath,
                metadata: meta
            )
            addToHistory(record)
            ClipboardSounds.playCopy()
            return
        }
    }

    private func applyOCR(_ id: UUID, text: String) {
        guard let i = history.firstIndex(where: { $0.id == id }) else { return }
        let old = history[i]
        history[i] = ClipboardRecord(
            id: old.id, type: old.type, timestamp: old.timestamp,
            sourceBundleID: old.sourceBundleID, sourceAppName: old.sourceAppName,
            textSnippet: old.textSnippet, thumbnailPath: old.thumbnailPath,
            payloadPath: old.payloadPath, ocrText: text,
            pinboardID: old.pinboardID, metadata: old.metadata
        )
        let updated = history[i]
        Task { await DatabaseService.shared.insertClipboardRecord(updated) }
    }

    // MARK: - History

    /// D4 note: checked every `ClipboardRecord(...)` construction on the capture path (the pasteboard
    /// monitor's record-building sites above this function) — none of them passes `pinboardID:`, so a
    /// freshly captured record's `pinboardID` is always the model's own `nil` default. A new clip is
    /// therefore NEVER auto-filed into a locked board at capture time; the only paths that can assign a
    /// board are `addItemToPinboard` (explicit user action) and `mergeRecords`/`appendToMergedRecord`
    /// (which copy an existing record's `pinboardID`, itself never auto-set). Left unchanged, as instructed.
    func addToHistory(_ record: ClipboardRecord) {
        let stamped = ClipboardRecord(
            id: record.id, type: record.type, timestamp: Date(),
            sourceBundleID: record.sourceBundleID ?? getSourceAppBundleID(),
            sourceAppName: record.sourceAppName ?? getSourceAppName(),
            textSnippet: record.textSnippet, thumbnailPath: record.thumbnailPath,
            payloadPath: record.payloadPath, ocrText: record.ocrText,
            pinboardID: record.pinboardID, metadata: record.metadata
        )
        history.insert(stamped, at: 0)
        trimToCap()
        Task { await DatabaseService.shared.insertClipboardRecord(stamped) }
        LinkPreviewFetcher.shared.enqueue(stamped)      // D4b: a no-op unless the opt-in switch is on
    }

    /// D4b — a link preview arrived (or its fetch failed): patch the row's metadata in memory when the history
    /// holds it, and on disk either way, so every surface shows the same title and image.
    func applyLinkPreview(id: UUID, patch: [String: String]) {
        if let i = history.firstIndex(where: { $0.id == id }) {
            let r = Self.patching(history[i], metadata: patch)
            history[i] = r
            Task { _ = await DatabaseService.shared.updateClipboardRecord(r) }
        } else {
            Task {
                guard let r = await DatabaseService.shared.fetchClipboardRecord(id: id) else { return }
                _ = await DatabaseService.shared.updateClipboardRecord(Self.patching(r, metadata: patch))
            }
        }
    }

    /// `metadata` is immutable on the record (every writer rebuilds it, like `togglePin`): the same record with
    /// `patch` merged over its metadata.
    nonisolated static func patching(_ r: ClipboardRecord, metadata patch: [String: String]) -> ClipboardRecord {
        var meta = r.metadata
        for (k, v) in patch { meta[k] = v }
        return ClipboardRecord(id: r.id, type: r.type, timestamp: r.timestamp, sourceBundleID: r.sourceBundleID,
                               sourceAppName: r.sourceAppName, textSnippet: r.textSnippet, thumbnailPath: r.thumbnailPath,
                               payloadPath: r.payloadPath, ocrText: r.ocrText, pinboardID: r.pinboardID, metadata: meta)
    }

    /// Delete with the record in hand: removes a locked row's sealed files whether or not the row is
    /// inside the capped history (the Library loads rows the history no longer holds).
    func deleteRecord(_ record: ClipboardRecord) {
        if record.isLocked {
            let ops = BoardLockKeys.fileOps
            for path in BoardLock.sealedFiles(of: record) { try? ops.remove(path) }
        }
        deleteRecord(record.id)
    }

    func deleteRecord(_ id: UUID) {
        // D4: a locked row's content lives only in its sealed envelope/payload/thumbnail files under
        // BoardLockKeys.lockedDir() — the DB row carries no plaintext to lose, but those files are the
        // only copy of the ciphertext, so they must go with the row or they become orphaned forever.
        // (Before D4, deleteRecord never removed any payload/thumbnail file for an ordinary row either —
        // this only adds cleanup for the locked case that D4 introduces.)
        if let record = history.first(where: { $0.id == id }), record.isLocked {
            let ops = BoardLockKeys.fileOps
            for path in BoardLock.sealedFiles(of: record) {
                try? ops.remove(path)
            }
        }
        history.removeAll { $0.id == id }
        if selectedItemID == id { selectedItemID = history.first?.id }
        Task { await DatabaseService.shared.deleteClipboardRecord(id) }
    }

    /// Excludes an application from being recorded and purges existing items from history.
    func excludeApp(bundleID: String?, appName: String?) {
        guard let id = (bundleID?.isEmpty == false ? bundleID : appName), !id.isEmpty else { return }
        let current = UserDefaults.standard.string(forKey: "clipboard.customExcludedApps") ?? ""
        var items = current.split(separator: ",").map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }.filter { !$0.isEmpty }
        if !items.contains(id) {
            items.append(id)
            let updated = items.joined(separator: ", ")
            UserDefaults.standard.set(updated, forKey: "clipboard.customExcludedApps")
        }
        let target = id.lowercased()
        let matchingIDs = history.filter {
            ($0.sourceBundleID?.lowercased().contains(target) == true) ||
            ($0.sourceAppName?.lowercased().contains(target) == true)
        }.map(\.id)
        for mid in matchingIDs {
            deleteRecord(mid)
        }
    }


    /// The ONE reader of `clipboard.maxHistory` (0 = no cap): the in-memory cap AND how many rows are loaded
    /// from the database at launch — before 2026-10-12 the load was a hard-coded 1 000, so "5 000 items"
    /// never loaded more than 1 000 and "Unlimited" meant 1 000.
    var historyCap: Int { UserDefaults.standard.object(forKey: "clipboard.maxHistory") as? Int ?? 1000 }

    /// Settings-wired cap (`clipboard.maxHistory`).
    func trimToCap() {
        let cap = historyCap
        guard cap > 0 else { return }
        if history.count > cap {
            history = Array(history.prefix(cap))
        }
    }

    /// Settings-wired expiry (`clipboard.autoDeleteDays`), run at launch.
    private func purgeExpired() {
        let days = UserDefaults.standard.object(forKey: "clipboard.autoDeleteDays") as? Int ?? 30
        guard days > 0 else { return }
        let cutoff = Date().addingTimeInterval(TimeInterval(-days * 24 * 3600))
        history.removeAll { $0.timestamp < cutoff }
        Task { [cutoff] in
            await DatabaseService.shared.deleteClipboardRecords(olderThan: cutoff)
        }
    }

    func filteredHistory() -> [ClipboardRecord] {
        var list = history

        // 1. Slice filter
        switch selectedSlice {
        case .all:
            break
        case .pinned:
            list = list.filter { $0.isPinned }
        case .saved:
            list = list.filter { $0.isSavedSnippet }
        case .merged:
            list = list.filter { $0.type == .merged }
        }

        // 2. Type filter
        if let filter = selectedTypeFilter {
            list = list.filter { $0.type == filter }
        }

        // 3. Date filter
        if dateFilter != .allTime {
            list = list.filter { dateFilter.matches($0.timestamp) }
        }

        // 4. Source App filter
        if let app = sourceAppFilter, !app.isEmpty {
            list = list.filter { $0.sourceAppName == app }
        }

        // 5. Search query
        if !searchText.isEmpty {
            list = list.filter { r in
                (r.textSnippet?.localizedCaseInsensitiveContains(searchText) ?? false)
                    || (r.ocrText?.localizedCaseInsensitiveContains(searchText) ?? false)
                    || (r.sourceAppName?.localizedCaseInsensitiveContains(searchText) ?? false)
                    || (r.customTitle?.localizedCaseInsensitiveContains(searchText) ?? false)
            }
        }

        // 6. Sort order
        switch sortOrder {
        case .newest:
            list.sort { $0.timestamp > $1.timestamp }
        case .oldest:
            list.sort { $0.timestamp < $1.timestamp }
        case .mostUsed:
            list.sort {
                if $0.usageCount != $1.usageCount {
                    return $0.usageCount > $1.usageCount
                }
                return $0.timestamp > $1.timestamp
            }
        }

        return list
    }

