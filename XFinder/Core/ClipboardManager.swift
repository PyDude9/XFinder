/// Clipboard ingest: event-driven pasteboard monitoring (zero polling),
/// privacy filtering, disk-offloaded payloads, Vision OCR, Paste Stack.
@MainActor
@Observable
final class ClipboardManager {
    static let shared = ClipboardManager()

    var history: [ClipboardRecord] = []
    var pinboards: [Pinboard] = Pinboard.defaultPinboards
    var currentPinboardID: UUID?
    var selectedItemID: UUID?
    var selectedSlice: ClipboardSlice = .all
    var sortOrder: ClipboardSortOrder = .newest
    var dateFilter: ClipboardDateFilter = .allTime
    var sourceAppFilter: String? = nil
    var selectedTypeFilter: ContentType? = nil
    var searchText: String = ""
    var pasteStack = PasteStack()

    var multiSelectedIDs: Set<UUID> = []
    var isMultiSelectActive: Bool = false

    var allSourceApps: [String] {
        let set = Set(history.compactMap { $0.sourceAppName }.filter { !$0.isEmpty })
        return Array(set).sorted()
    }

    /// Sliding window (10s) deduplication cache.
    private var recentHashes: [(hash: String, date: Date)] = []

    private func isDuplicateContent(_ string: String) -> Bool {
        let hash = SHA256.hash(data: Data(string.utf8)).map { String(format: "%02x", $0) }.joined()
        let now = Date()
        recentHashes.removeAll { now.timeIntervalSince($0.date) > 10 }
        if recentHashes.contains(where: { $0.hash == hash }) {
            return true
        }
        recentHashes.append((hash: hash, date: now))
        return false
    }

    /// Last non-XFinder frontmost app — the paste target for ⌘V synthesis.
    private(set) var lastExternalPID: pid_t?

    // MARK: - Privacy (guide §7)

    /// Pasteboard types or keywords marking content as secret / transient — never ingested.
    private static let sensitiveTypeKeywords: [String] = [
        "concealed",
        "transient",
        "autogenerated",
        "onepassword",
        "bitwarden",
        "keepass",
        "lastpass",
        "dashlane",
        "clipping",
        "pasteboard generator",
        "cleanmymac"
    ]

