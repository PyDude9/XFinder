import XCTest

/// Clipboard content classification and the privacy filter.
///
/// The privacy tests matter most: if the filter ever regresses, XFinder starts
/// recording passwords. That is the one failure in this app that cannot be
/// undone by the user.
///
/// Mirrors `ClipboardClassifier.classify` and `ClipboardManager`'s filter sets.
final class ClipboardClassifierTests: XCTestCase {

    enum ContentType { case text, code, image, link, color, file }

    private static let hexRE = try? NSRegularExpression(
        pattern: #"^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$"#)

    private func classify(_ text: String) -> ContentType {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.isEmpty else { return .text }
        if t.count <= 9, let re = Self.hexRE,
           re.firstMatch(in: t, range: NSRange(t.startIndex..., in: t)) != nil {
            return .color
        }
        if t.count < 2000, let u = URL(string: t),
           let scheme = u.scheme?.lowercased(), ["http", "https"].contains(scheme) {
            return .link
        }
        if looksLikeCode(t) { return .code }
        return .text
    }

    private func looksLikeCode(_ t: String) -> Bool {
        guard t.count > 8, t.contains("\n") || t.contains(";") else { return false }
        let markers = ["func ", "class ", "struct ", "import ", "let ", "var ",
                       "def ", "return ", "{", "}", "=>", "func(", "#include",
                       "public ", "private ", "func\t", "if let ", "guard let "]
        let hits = markers.filter { t.contains($0) }.count
        if hits >= 2 { return true }
        if hits == 1 && (t.contains("{") || t.contains(";")) { return true }
        return false
    }

    // MARK: Colours

    func testSixDigitHexIsColour() {
        XCTAssertEqual(classify("#1F6FEB"), .color)
    }

    func testShorthandHexIsColour() {
        XCTAssertEqual(classify("#fff"), .color)
    }

    func testHexWithAlphaIsColour() {
        XCTAssertEqual(classify("#1F6FEB80"), .color)
    }

    /// A hashtag is not a colour — five chars, not a valid hex length.
    func testHashtagIsNotAColour() {
        XCTAssertNotEqual(classify("#swift"), .color)
    }

    // MARK: Links

    func testHTTPSIsLink() {
        XCTAssertEqual(classify("https://example.com/a?b=c"), .link)
    }

    /// Only http/https count. A `file:` or `javascript:` URL must not be
    /// treated as a web link.
    func testNonWebSchemeIsNotLink() {
        XCTAssertNotEqual(classify("file:///etc/passwd"), .link)
        XCTAssertNotEqual(classify("javascript:alert(1)"), .link)
    }

    func testPlainSentenceIsNotLink() {
        XCTAssertEqual(classify("just some words here"), .text)
    }

    // MARK: Code

    func testSwiftSnippetIsCode() {
        XCTAssertEqual(classify("func hello() {\n    return 1\n}"), .code)
    }

    /// Prose that happens to contain a brace must not be misread as code.
    func testProseWithOneBraceIsNotCode() {
        XCTAssertEqual(classify("I wrote { and then went home"), .text,
                       "A single brace with no code markers is prose")
    }

    func testShortStringIsNeverCode() {
        XCTAssertEqual(classify("a;b"), .text, "Too short to be a code block")
    }

    // MARK: Whitespace / empties

    func testEmptyAndWhitespaceAreText() {
        XCTAssertEqual(classify(""), .text)
        XCTAssertEqual(classify("   \n  "), .text)
    }

    func testSurroundingWhitespaceIsIgnored() {
        XCTAssertEqual(classify("   #1F6FEB  "), .color)
    }
}

/// The privacy filter — the rules that stop XFinder recording secrets.
final class ClipboardPrivacyTests: XCTestCase {

    /// Mirrors `ClipboardManager.sensitiveTypes`.
    static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "org.nspasteboard.TransientType",
        "com.agilebits.onepassword",
        "com.bitwarden.pasteboard",
    ]

    /// Mirrors `ClipboardManager.excludedBundleIDs`.
    static let excludedBundleIDs: Set<String> = [
        "com.agilebits.onepassword4",
        "com.agilebits.onepassword7",
        "com.1password.1password",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
        "com.dashlane.Dashlane",
        "com.lastpass.LastPass",
        "com.apple.keychainaccess",
    ]

    private func shouldCapture(types: Set<String>,
                               bundleID: String?,
                               excludePasswordManagers: Bool) -> Bool {
        guard types.isDisjoint(with: Self.sensitiveTypes) else { return false }
        if excludePasswordManagers, let id = bundleID,
           Self.excludedBundleIDs.contains(id) { return false }
        return true
    }

    /// `ConcealedType` is the convention every password manager sets. It must
    /// be honoured **even when the bundle-ID blocklist is switched off** —
    /// that toggle is about known apps, not about ignoring the standard.
    func testConcealedTypeIsRejectedEvenWithFilterOff() {
        let blocked = shouldCapture(types: ["org.nspasteboard.ConcealedType"],
                                    bundleID: "com.example.unknown",
                                    excludePasswordManagers: false)
        XCTAssertFalse(blocked, "Concealed content must never be recorded")
    }

    func testAutoGeneratedAndTransientAreRejected() {
        for t in ["org.nspasteboard.AutoGeneratedType", "org.nspasteboard.TransientType"] {
            XCTAssertFalse(shouldCapture(types: [t], bundleID: nil,
                                         excludePasswordManagers: false),
                           "\(t) must never be recorded")
        }
    }

    func testKnownPasswordManagersAreRejected() {
        for id in Self.excludedBundleIDs {
            XCTAssertFalse(shouldCapture(types: ["public.utf8-plain-text"],
                                         bundleID: id,
                                         excludePasswordManagers: true),
                           "\(id) is a password manager and must be skipped")
        }
    }

    /// With the toggle off, an ordinary copy from a password manager is
    /// allowed — that is the documented meaning of the switch.
    func testBlocklistIsHonouredOnlyWhenEnabled() {
        XCTAssertTrue(shouldCapture(types: ["public.utf8-plain-text"],
                                    bundleID: "com.1password.1password",
                                    excludePasswordManagers: false))
    }

    func testOrdinaryCopyIsCaptured() {
        XCTAssertTrue(shouldCapture(types: ["public.utf8-plain-text"],
                                    bundleID: "com.apple.Safari",
                                    excludePasswordManagers: true))
    }

    /// A payload carrying BOTH a normal and a sensitive type is still secret.
    func testMixedTypesStillRejected() {
        XCTAssertFalse(shouldCapture(
            types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"],
            bundleID: "com.apple.Safari",
            excludePasswordManagers: true))
    }

    // MARK: - Luhn Credit Card Detection Tests

    private func looksLikeCreditCard(_ t: String) -> Bool {
        let trimmed = t.trimmingCharacters(in: .whitespacesAndNewlines)
        let digits = trimmed.filter { $0.isNumber }
        guard (13...19).contains(digits.count),
              digits.count == trimmed.filter({ !$0.isWhitespace && $0 != "-" }).count else {
            return false
        }
        var sum = 0
        let reversed = digits.reversed().map { Int(String($0)) ?? 0 }
        for (idx, digit) in reversed.enumerated() {
            if idx % 2 == 1 {
                let doubled = digit * 2
                sum += doubled > 9 ? doubled - 9 : doubled
            } else {
                sum += digit
            }
        }
        return sum % 10 == 0
    }

    func testValidCreditCardIsDetected() {
        // Standard Visa test number: 4532 0151 1283 0366
        XCTAssertTrue(looksLikeCreditCard("4532 0151 1283 0366"))
        XCTAssertTrue(looksLikeCreditCard("4532-0151-1283-0366"))
        XCTAssertTrue(looksLikeCreditCard("4532015112830366"))
    }

    func testInvalidCreditCardIsIgnored() {
        // Phone number, short digits, or invalid checksum
        XCTAssertFalse(looksLikeCreditCard("0912345678"))
        XCTAssertFalse(looksLikeCreditCard("4532 0151 1283 0367")) // Invalid checksum
        XCTAssertFalse(looksLikeCreditCard("Invoice #12345678901234"))
    }

    func testCustomExcludedBundleIDs() {
        let customList = ["com.secret.internal", "com.banking.app"]
        XCTAssertTrue(customList.contains("com.secret.internal"))
        XCTAssertFalse(customList.contains("com.apple.Safari"))
    }
}
